/**
 * Renderiza todo o conjunto da interface (HUD, mapa, batalha, joystick e ranking).
 * @param {HTMLElement} raiz
 * @param {object} estado
 * @param {object} [opcoes={}]
 */
export function renderizarJogo(raiz, estado, opcoes = {}) {
  if (!raiz) return;

  injetarEstilosBase();

  // 1. HUD (RF02, RF21, RF31, RF34)
  let containerHud = raiz.querySelector('.hud-container');
  if (!containerHud) {
    containerHud = document.createElement('div');
    raiz.insertBefore(containerHud, raiz.firstChild);
  }
  renderizarHud(containerHud, estado);

  // 2. Mapa
  let containerMapa = raiz.querySelector('.container-mapa');
  if (!containerMapa) {
    containerMapa = document.createElement('div');
    raiz.appendChild(containerMapa);
  }
  renderizarMapa(containerMapa, estado, opcoes);

  // 3. Batalha e Cartas (RF19)
  let containerBatalha = raiz.querySelector('.painel-batalha');
  if (!containerBatalha) {
    containerBatalha = document.createElement('div');
    raiz.appendChild(containerBatalha);
  }
  renderizarBatalha(containerBatalha, estado, opcoes);

  // 4. Joystick Virtual
  let containerJoystick = raiz.querySelector('.joystick-container-wrapper');
  if (!containerJoystick) {
    containerJoystick = document.createElement('div');
    containerJoystick.className = 'joystick-container-wrapper';
    raiz.appendChild(containerJoystick);

    if (joystickInstancia) {
      joystickInstancia.destruir();
    }
    joystickInstancia = criarJoystick(containerJoystick, opcoes);
  }

  // 5. Ranking (se aplicável)
  if (opcoes.ranking) {
    let containerRanking = raiz.querySelector('.painel-ranking');
    if (!containerRanking) {
      containerRanking = document.createElement('div');
      raiz.appendChild(containerRanking);
    }
    renderizarRanking(containerRanking, opcoes.ranking);
  }
}
